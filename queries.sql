use AdventureWorks2022

-- Person

--  Q1) How many people are recorded in the datebase for each PersonType

SELECT Count(P.Persontype) as 'Count of PersonType',
P.PersonType

From Person.Person as P

Group BY
P.PersonType

--Q2)   Which people have an email address associated with their account? Display first name, last name and email address.

Select
P.FirstName,
P.lastname,
E.EmailAddress
From Person.Person as P
Join Person.EmailAddress as E
ON p.BusinessEntityID = E.BusinessEntityID

--  Q3) Which cities have more than 100 people registered against them?


Select 
Count(Distinct P.BusinessEntityID) 'Count of People',
A.City

From Person.Person as P
Inner Join Person.BusinessEntityAddress as B
On P.BusinessEntityID =B.BusinessEntityID
Inner Join Person.Address A
ON B.AddressID = A.AddressID

Group BY
A.City

HAVING

Count(Distinct P.BusinessEntityID) > 100


-- Production

--  Q4) Which product categories have the highest average list price? Show category name and average list price.


Select 

C.Name AS 'Product Category Name',
AVG(P.ListPrice) 'AVG List Price'

From Production.Product P
Inner Join Production.ProductSubcategory S
ON P.ProductSubcategoryID = S.ProductSubcategoryID
Inner Join Production.ProductCategory C
On S.ProductCategoryID = C.ProductCategoryID

Group BY
C.Name

Order By
AVG(P.ListPrice) DESC

--  Q5 Which products have a list price greater than $1,000? Display product name, product number and list price.

Select

P.Name as 'Product Name',
P.ProductNumber as 'Product Number',
P.ListPrice

From Production.Product P

Where P.ListPrice >1000

Order BY P.ListPrice DESC

--  Q6) Which products have never been sold? Display product name and product number.

Select 

P.Name AS 'Product Name',
p.ProductNumber AS 'Product Number'

From production.Product p
Left join sales.SalesOrderDetail s
ON P.ProductID = S.ProductID

Where S.ProductID IS NULL


--  Q7) Which product subcategories contain more than 10 products? Display subcategory name and product count.

Select 
PS.Name as 'Subcategory Name',
Count(P.NAME) AS 'Product Count'
From Production.Product as P
Inner Join Production.ProductSubcategory as PS
ON P.ProductSubcategoryID = PS.ProductSubcategoryID

Group BY
PS.Name

Having
Count(P.NAME) > 10

Order BY 
Count(P.NAME) DESC

-- Sales

--  Q8) How many sales orders has each customer placed? Display customer ID and order count.

Select

c.CustomerID,
Count(H.SalesOrderID) as 'Count of Sales Orders'

From Sales.Customer as C
Inner Join Sales.SalesOrderHeader as H
ON C.CustomerID = H.CustomerID

Group BY 
c.CustomerID

Order By
Count(H.SalesOrderID)  DESC

--  Q9) 	How many sales orders were placed in each month of 2013?

Select 

DATENAME(MONTH,H.OrderDate) as 'Order Month',
Count(H.OrderDate) as 'Number of Sales Orders'
From Sales.SalesOrderHeader H

Where H.OrderDate >= '2013-01-01' AND H.OrderDate < '2014-01-01'

Group BY
DATENAME(MONTH,H.OrderDate) ,
MONTH(H.OrderDate)

Order By
MONTH(H.OrderDate) ASC

-- Q10) What is the total sales value generated by each territory?


Select 
T.Name as 'Territory',
Sum(H.TotalDue) as 'Total Sales Value'

From Sales.SalesOrderHeader as H
Inner Join Sales.SalesTerritory as T
ON H.TerritoryID = T.TerritoryID

Group BY
T.Name

--  Q11) Which salespeople have generated more than $1 million in sales? Display salesperson ID and total sales value.

Select 

OH.SalesPersonID,
SUM(OH.TotalDue) as 'Total Sales Value'

From Sales.SalesPerson as SP
Inner JOIN Sales.SalesOrderHeader as OH
ON SP.TerritoryID = OH.TerritoryID

Where OH.SalesPersonID IS NOT NULL

Group BY
OH.SalesPersonID

Having SUM(OH.TotalDue) >1000000

Order BY SUM(OH.TotalDue) DESC



-- Q12) Which products have generated more than $100,000 in total sales revenue? Display product name and total sales revenue.

Select 
P.Name  as 'Product Name',
SUM(S.lineTotal) as 'Total Sales'

From
Production.Product P
Join Sales.SalesOrderDetail S
ON P.ProductID = S.ProductID
Group BY
P.Name

Having
SUM(S.lineTotal) >100000

Order BY
SUM(S.lineTotal) DESC

-- Human Resources and cross-schema analysis

-- Q13) How many current employees work in each department?

Select 

D.Name as 'Department Name',
Count(*) as 'Number of Current Employees'

From  HumanResources.Employee E
Inner Join HumanResources.EmployeeDepartmentHistory H
ON E.BusinessEntityID = H.BusinessEntityID
Inner Join HumanResources.Department D
ON H.DepartmentID = D.DepartmentID


Where H.EndDate IS NULL

Group BY
D.Name

Order BY
Count(*) DESC

-- Q14) What is the total sales revenue for each product category?


Select 

PC.Name as 'Product Category',
Sum(OD.lineTotal) as 'Total Sales Revenue'

from  Production.ProductCategory as PC
Inner JOIN  Production.ProductSubcategory as SC
ON PC.ProductCategoryID = SC.ProductCategoryID
Inner Join Production.Product as P
ON P.ProductSubcategoryID = SC.ProductSubcategoryID
Inner Join Sales.SalesOrderDetail as OD
on P.ProductID= OD.ProductID

Group BY
PC.Name

-- Q15) What is the average vacation hours entitlement for employees in each job title?

Select
E.JobTitle,
AVG(E.VacationHours) as 'Average Vacation Hours Entitlement'

From HumanResources.Employee as E

Group BY
E.JobTitle

Order BY
AVG(E.VacationHours) DESC